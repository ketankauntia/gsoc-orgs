import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const organizationsDir = path.join(root, "new-api-details", "organizations");
const outputPath = path.join(root, "lib", "generated", "organization-slugs.ts");
const excluded = new Set(["index.json", "metadata.json"]);
const files = fs.readdirSync(organizationsDir)
  .filter((file) => file.endsWith(".json") && !excluded.has(file))
  .sort();

// Slugs only: the documents themselves are read at runtime (lib/catalog-data.ts)
// because bundling them pushed the Cloudflare Worker past its size limit.
const entries = files.map((file) => `  ${JSON.stringify(file.slice(0, -5))},`);

const source = `// Generated by scripts/generate-organization-imports.mjs. Do not edit manually.
export const organizationSlugs: ReadonlySet<string> = new Set([
${entries.join("\n")}
]);
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, source);
console.log(`Generated ${files.length} organization slugs.`);
